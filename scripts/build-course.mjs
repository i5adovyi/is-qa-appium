import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { lstat, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { allowedPage, courseAssets, loadCatalog, loadPage, readWithinRoot } from './course-content.mjs'

const projectRoot = fileURLToPath(new URL('../', import.meta.url))
const marker = '.course-build.json'

export async function buildCourse({ root = projectRoot, destination = path.join(root, 'dist') } = {}) {
    root = path.resolve(root)
    destination = path.resolve(destination)
    if (destination === root || root.startsWith(`${destination}${path.sep}`)) throw new Error('Output must not replace the project')
    const existing = await lstat(destination).catch(error => { if (error.code !== 'ENOENT') throw error })
    if (existing) {
        if (!existing.isDirectory() || existing.isSymbolicLink()) throw new Error('Output must be a real directory')
        const previous = await readFile(path.join(destination, marker), 'utf8').catch(() => '')
        if (previous !== '{"format":"mobile-automation-course-v1"}\n') throw new Error('Refusing to replace a directory not generated by this builder')
    }
    // Git's tracked-file list excludes local credentials, downloaded apps,
    // logs and untracked notes. The reader allowlist further restricts it.
    const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean)
    const pages = tracked.filter(allowedPage).sort()
    const catalog = await loadCatalog(root)
    const required = [
        ...catalog.lessons.flatMap(lesson => [lesson.path, lesson.path.replace('/lessons/', '/solutions/')]),
        ...catalog.library.map(item => item.path),
        ...(catalog.challenges ?? []).map(item => item.path),
        ...(catalog.assignments ?? []).map(item => item.path),
        ...(catalog.browserstackLessons ?? []).map(item => item.path),
        ...catalog.practiceCollections.map(item => item.path),
    ]
    for (const name of required) {
        if (!pages.includes(name)) throw new Error(`Stage the new course file before building: ${name}`)
    }
    await mkdir(path.dirname(destination), { recursive: true })
    const staging = await mkdtemp(path.join(path.dirname(destination), '.course-build-'))
    try {
        await mkdir(path.join(staging, 'data/pages'), { recursive: true })
        const pageFiles = {}
        for (const name of pages) {
            const target = `data/pages/${createHash('sha256').update(name).digest('hex')}.json`
            await writeFile(path.join(staging, target), JSON.stringify(await loadPage(root, name)))
            pageFiles[name] = target
        }
        await writeFile(path.join(staging, 'data/catalog.json'), JSON.stringify({ ...catalog, pageFiles }))
        for (const asset of courseAssets) {
            let source = await readWithinRoot(root, `course/${asset}`)
            if (asset === 'index.html') {
                const setting = '<meta name="course-data-mode" content="local">'
                if (!source.includes(setting)) throw new Error('Missing reader data-mode setting')
                source = source.replace(setting, '<meta name="course-data-mode" content="static">')
            }
            await writeFile(path.join(staging, asset), source)
        }
        await writeFile(path.join(staging, marker), '{"format":"mobile-automation-course-v1"}\n')
        if (existing) await rm(destination, { recursive: true })
        await rename(staging, destination)
        return { destination, pages: pages.length, lessons: catalog.lessons.length, practice: catalog.practice.length, assignments: catalog.assignments?.length ?? 0 }
    } finally {
        await rm(staging, { recursive: true, force: true })
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        const result = await buildCourse()
        console.log(`Static course built in ${result.destination}: ${result.lessons} lessons, ${result.practice} practice items, ${result.assignments} topic assignments, ${result.pages} readable files.\nPreview with npm run course:preview. Tests still run in your project terminal.`)
    } catch (error) {
        console.error(`Course build failed: ${error.message}`)
        process.exitCode = 1
    }
}
