import path from 'node:path'
import { cp, lstat, mkdtemp, readFile, readdir, rename, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { getSiteProfile, requireRealDirectory } from './site-profile.mjs'

const projectRoot = fileURLToPath(new URL('../', import.meta.url))
const marker = '{"format":"mobile-automation-course-v1"}\n'

async function verifyBuild(directory) {
    await requireRealDirectory(directory)
    // A static export must not contain links to files outside its own directory.
    const inspect = async current => {
        for (const name of await readdir(current)) {
            const filename = path.join(current, name)
            const entry = await lstat(filename)
            if (entry.isSymbolicLink() || (!entry.isFile() && !entry.isDirectory())) {
                throw new Error('The static build must contain only regular files and directories')
            }
            if (entry.isDirectory()) await inspect(filename)
        }
    }
    await inspect(directory)
    if (await readFile(path.join(directory, '.course-build.json'), 'utf8') !== marker) {
        throw new Error('Refusing to use a directory not generated by the course builder')
    }
}

export async function prepareSite({ root = projectRoot, profile }) {
    root = path.resolve(root)
    const result = await getSiteProfile({ root, profile })
    if (!result.manifest.project_id) {
        throw new Error('This profile is not registered. Use native Sites registration in the intended OpenAI account and persist the returned ID before preparing it.')
    }
    const source = path.join(root, 'dist')
    const destination = path.join(result.directory, 'dist')
    await verifyBuild(source)
    const previous = await requireRealDirectory(destination, { optional: true })
    if (previous) await verifyBuild(destination)
    const staging = await mkdtemp(path.join(result.directory, '.course-site-'))
    try {
        await cp(source, staging, { recursive: true })
        // Preserve the profile manifest, Site source checkout and its Git history.
        if (previous) await rm(destination, { recursive: true })
        await rename(staging, destination)
    } finally {
        await rm(staging, { recursive: true, force: true })
    }
    return result
}

export function parsePrepareArgs(args) {
    if (args.length !== 2 || args[0] !== '--profile') {
        throw new Error('Choose a Site explicitly: npm run course:sites -- --profile <profile>')
    }
    return args[1]
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        const result = await prepareSite({ profile: parsePrepareArgs(process.argv.slice(2)) })
        console.log(`Site source prepared at ${result.directory}\nSite: ${result.manifest.project_id}\nThis does not publish. Continue the native Sites source and publishing workflow for this profile.`)
    } catch (error) {
        console.error(`Site preparation failed: ${error.message}`)
        process.exitCode = 1
    }
}
